// التطبيع العربي — Arabic Normalization
// للحفاظ على الاسم الأصلي مع تمكين البحث
// ─────────────────────────────────────────────

/**
 * يطبّع النص العربي للبحث دون تغيير الأصل:
 * - إزالة التشكيل
 * - توحيد أ / إ / آ → ا
 * - ى → ي
 * - توحيد المسافات
 * - إزالة التطويل (ـ)
 */
export function normalizeArabic(text: string): string {
  if (!text) return "";

  return text
    .trim()
    // إزالة التشكيل
    .replace(/[\u0617-\u061A\u064B-\u0652\u0670\u0640]/g, "")
    // توحيد الألف
    .replace(/[\u0622\u0623\u0625\u0671]/g, "ا")
    // ى → ي
    .replace(/\u0649/g, "ي")
    // ة → ه (اختياري للبحث المرن)
    .replace(/\u0629/g, "ه")
    // توحيد المسافات
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
}
